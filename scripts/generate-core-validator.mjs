import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { _ } from 'ajv/dist/compile/codegen/index.js';
import { build } from 'esbuild';
import { uintFormats } from '../src/integration/unsigned-decimal.mjs';

// Ajv's Function constructor is confined to this Node build step. Only the
// resulting ordinary ESM functions are imported by the browser application.
export async function generateCoreValidator({ check = false } = {}) {
  const directory = new URL('../src/integration/', import.meta.url);
  const raw = await readFile(new URL('core.schema.json', directory), 'utf8');
  const ajv = new Ajv2020({
    strict: false,
    allErrors: true,
    code: { source: true, esm: true, lines: true, formats: _`uintFormats` },
  });
  addFormats(ajv);
  for (const [name, format] of Object.entries(uintFormats)) ajv.addFormat(name, format);
  const validator = ajv.compile(JSON.parse(raw));
  const source = `import { uintFormats } from './unsigned-decimal.mjs';\n${standaloneCode(ajv, validator)}`;
  // Bundle only the standalone function's small, static helpers. This also
  // converts Ajv's generated CommonJS helper references into browser ESM.
  const result = await build({
    stdin: { contents: source, resolveDir: fileURLToPath(directory), sourcefile: 'core-standalone.mjs' },
    bundle: true, write: false, format: 'esm', platform: 'browser', target: 'es2022',
    legalComments: 'none',
  });
  const hash = createHash('sha256').update(raw).digest('hex');
  const generated = `// Generated by scripts/generate-core-validator.mjs; do not edit.\n// Schema SHA-256: ${hash}\n${result.outputFiles[0].text}`;
  const output = new URL('core-validator.generated.mjs', directory);
  if (check) {
    if (await readFile(output, 'utf8') !== generated) throw new Error('Core validator is stale. Run node scripts/generate-core-validator.mjs.');
  } else if (await readFile(output, 'utf8').catch(() => '') !== generated) {
    await writeFile(output, generated);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  await generateCoreValidator({ check: process.argv.includes('--check') });
  console.log(process.argv.includes('--check') ? 'Core validator is current.' : 'Core validator generated.');
}
